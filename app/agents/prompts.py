def tools_block(role: str) -> str:
    lines = ["ДОСТУПНЫЕ ИНСТРУМЕНТЫ:"]
    for name, args, desc in ROLE_TOOLS[role]:
        a = ", ".join(f'"{k}": {v}' for k, v in args.items())
        lines.append(f'- {name}({a}) — {desc}')
    return "\n".join(lines)
